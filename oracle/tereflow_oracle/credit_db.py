def imf_codelist(cfg: dict, log=print) -> dict:
    try:
        return C.parse_imf_codelist(C.http_get(C.imf_codelist_url(cfg), "application/xml"))
    except Exception as e:
        log(f"IMF codelist not re-verified this run ({e})")
        return {}


def discover_imf(conn, cfg: dict, country: str, codelist: dict, log=print) -> dict:
    """Ask the IMF what exists for this country, then register only the configured credit indicators that really exist.

    Returns {'found': n, 'freq': 'M'|'Q'|'A'|None, 'missing': [codes]}. Nothing is registered for a country the IMF does not cover."""
    i = cfg["imf"]
    wanted = [x for x in i["indicators"] if x.get("active", True)]
    try:
        found = C.parse_imf_discovery(C.http_get(C.imf_discovery_url(cfg, country), "application/xml"))
    except Exception as e:
        log(f"{country}: IMF discovery failed ({e})")
        return {"found": 0, "freq": None, "missing": [w["code"] for w in wanted], "error": str(e)[:300]}
    have: dict[str, set[str]] = {}
    for s in found:
        if s.get("TYPE_OF_TRANSFORMATION") == i["transformation"]:
            have.setdefault(s.get("INDICATOR", ""), set()).add(s.get("FREQUENCY", ""))
    present = {w["code"]: have.get(w["code"], set()) for w in wanted}
    chosen = None
    for f in C.FREQ_ORDER:
        if wanted and all(f in present[w["code"]] for w in wanted):
            chosen = f
            break
    if chosen is None:
        best = max(C.FREQ_ORDER, key=lambda f: sum(1 for w in wanted if f in present[w["code"]]))
        chosen = best if any(best in present[w["code"]] for w in wanted) else None
    cur = conn.cursor()
    missing = []
    for w in wanted:
        if chosen is None or chosen not in present[w["code"]]:
            missing.append(w["code"])
            continue
        sid = f"{country}:IMF:{w['code']}:{chosen}"
        info = codelist.get(w["code"], {})
        note = (info.get("description") or "")[:2800] or "Definition not re-verified in this run."
        if info.get("name"):
            note = f"{info['name']}. {note}"
        key = f"{country}.{w['code']}.{i['transformation']}.{chosen}"
        cur.execute("SELECT 1 FROM app_cr_series WHERE id = :1", [sid])
        if cur.fetchone() is None:
            cur.execute("""INSERT INTO app_cr_series (id, country_iso3, source_key, source_name, databank, dataflow, mnemonic, series_name, data_family, sector_key, sector_name,
                           series_role, unit_label, unit_multiplier, unit_verified, frequency, measure_kind, kind_basis, definition_notes, endpoint_url, sort_order)
                           VALUES (:1,:2,'IMF',:3,:4,:5,:6,:7,'Monetary and Financial Statistics, Other Depository Corporations Survey',:8,:9,:10,
                                   'Domestic currency, whole units as published',:11,0,:12,'stock','source_definition',:13,:14,:15)""",
                        [sid, country, i["source_name"], i["agency"], i["dataflow"], key, info.get("name") or w["sector_name"], w["sector_key"], w["sector_name"], w["role"],
                         i["value_multiplier_to_millions"], chosen, note, C.imf_data_url(cfg, country, w["code"], chosen), w["sort_order"]])
        else:
            cur.execute("UPDATE app_cr_series SET definition_notes=:1, endpoint_url=:2 WHERE id=:3 AND kind_basis <> 'admin'", [note, C.imf_data_url(cfg, country, w["code"], chosen), sid])
    conn.commit()
    return {"found": len(have), "freq": chosen, "missing": missing}


