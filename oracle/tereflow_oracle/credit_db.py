def seed(conn, cfg: dict, reseed: bool = False, log=print) -> None:
    """Register the configured Bank of Ghana series, countries and the sector-to-trade map. Existing rows are kept unless reseed."""
    cur = conn.cursor()
    bog = cfg["bog"]
    iso = bog.get("country_iso3", "GHA")
    for s in bog["series"]:
        sid = f"{iso}:BOG:{s['mnemonic']}"
        cur.execute("SELECT 1 FROM app_cr_series WHERE id = :1", [sid])
        exists = cur.fetchone() is not None
        if exists and not reseed:
            continue
        vals = dict(id=sid, c=iso, sk="BOG", sn=bog["source_name"], db=bog["databank"], m=s["mnemonic"], sec=s["sector_key"], secn=s["sector_name"],
                    role=s["role"], so=s["sort_order"], url=C.bog_url(cfg, s["mnemonic"]), cur="GHS")
        if exists:
            cur.execute("""UPDATE app_cr_series SET sector_key=:sec, sector_name=:secn, series_role=:role, sort_order=:so, endpoint_url=:url,
                           updated_at=TO_CHAR(SYSTIMESTAMP AT TIME ZONE 'UTC','YYYY-MM-DD HH24:MI:SS') WHERE id=:id""",
                        {k: vals[k] for k in ("sec", "secn", "role", "so", "url", "id")})
        else:
            cur.execute("""INSERT INTO app_cr_series (id, country_iso3, source_key, source_name, databank, mnemonic, sector_key, sector_name, series_role,
                           sort_order, endpoint_url, currency, unit_multiplier, unit_verified) VALUES (:id,:c,:sk,:sn,:db,:m,:sec,:secn,:role,:so,:url,:cur,1,1)""", vals)
    for c in cfg["countries"]:
        cur.execute("SELECT 1 FROM app_cr_country_sources WHERE country_iso3 = :1", [c["iso3"]])
        if cur.fetchone() is None:
            cur.execute("INSERT INTO app_cr_country_sources (country_iso3, preferred_source, currency) VALUES (:1,:2,:3)", [c["iso3"], c.get("preferred_source", "auto"), c.get("currency")])
    for m in cfg["sector_map"]:
        cur.execute("SELECT 1 FROM app_cr_sector_map WHERE sector_key = :1", [m["sector_key"]])
        if cur.fetchone() is None:
            cur.execute("INSERT INTO app_cr_sector_map (sector_key, trade_scope, hs_prefixes, trade_flow, confidence, note) VALUES (:1,:2,:3,:4,:5,:6)",
                        [m["sector_key"], m["trade_scope"], m.get("hs_prefixes"), m.get("flow", "both"), m.get("confidence", "none"), m.get("note")])
    conn.commit()
    log("seeded credit configuration")


