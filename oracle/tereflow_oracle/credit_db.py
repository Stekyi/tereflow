def begin_run(conn, trigger: str, countries: list[str], backfill: bool, adopt: bool = True) -> tuple[str, list[str], bool]:
    """Adopt a run an admin requested from the dashboard, or start a new one. Returns (run_id, countries, backfill)."""
    cur = conn.cursor()
    cur.execute("SELECT id, countries, backfill FROM app_cr_runs WHERE status = 'requested' ORDER BY requested_at")
    rows = cur.fetchall() if adopt else []
    run_id = str(uuid.uuid4())
    if rows:
        run_id = rows[0][0]
        if rows[0][1]:
            countries = [x for x in str(rows[0][1]).split(",") if x]
        backfill = bool(rows[0][2]) or backfill
        cur.execute("UPDATE app_cr_runs SET status='running', started_at=:1 WHERE id=:2", [C.now_utc(), run_id])
        for other in rows[1:]:
            cur.execute("UPDATE app_cr_runs SET status='superseded', finished_at=:1, detail='Merged into a run that started at the same time.' WHERE id=:2", [C.now_utc(), other[0]])
    else:
        cur.execute(        "INSERT INTO app_cr_runs (id, run_kind, trigger_, status, backfill, countries, requested_at, started_at) VALUES (:1,'ingest',:2,'running',:3,:4,:5,:6)",
        [run_id, trigger, 1 if backfill else 0, ",".join(countries) or None, C.now_utc(), C.now_utc()])
    conn.commit()
    return run_id, countries, backfill


def finish_run(conn, run_id: str, stats: dict, notes: list[str]) -> str:
    status = "failed" if stats["series_ok"] == 0 and stats["series_failed"] else ("partial" if stats["series_failed"] else "success")
    cur = conn.cursor()
    cur.execute("""UPDATE app_cr_runs SET status=:1, finished_at=:2, series_ok=:3, series_failed=:4, obs_new=:5, obs_revised=:6, detail=:7 WHERE id=:8""",
                [status, C.now_utc(), stats["series_ok"], stats["series_failed"], stats["obs_new"], stats["obs_revised"], "\n".join(notes)[:2900] or None, run_id])
    conn.commit()
    return status


