def run(conn, cfg: dict, countries: list[str] | None = None, source: str = "all", backfill: bool = False, trigger: str = "manual",
        only_series: str | None = None, analyse_only: bool = False, dry_run: bool = False, log=print) -> dict:
    """The whole pipeline: load configuration, fetch (with backfill on request), validate, store, classify, analyse, log."""
    create_tables(conn, lambda *_: None)
    seed(conn, cfg, log=lambda *_: None)
    cur = conn.cursor()
    if not countries:
        cur.execute("SELECT country_iso3 FROM app_cr_country_sources WHERE is_active = 1 ORDER BY country_iso3")
        countries = [r[0] for r in cur]
    countries = [c.upper() for c in countries]
    run_id, countries, backfill = begin_run(conn, trigger, countries, backfill)
    stats = {"series_ok": 0, "series_failed": 0, "obs_new": 0, "obs_revised": 0}
    notes: list[str] = []
    imf_info: dict[str, dict] = {}
    try:
        codelist = imf_codelist(cfg, log) if source in ("all", "imf") and not analyse_only else {}
        if source in ("all", "file") and not analyse_only:
            q_loaded, q_ok, q_bad, q_notes = process_upload_queue(conn, cfg, run_id, backfill, log)
            stats["series_ok"] += q_ok
            stats["series_failed"] += q_bad
            notes.extend(q_notes)
            for c in sorted(q_loaded):
                if c not in countries:
                    countries.append(c)
        for country in countries:
            if not analyse_only:
                if source in ("all", "bog"):
                    cur.execute("SELECT id, source_key, mnemonic, endpoint_url, unit_multiplier, frequency FROM app_cr_series WHERE country_iso3=:1 AND source_key='BOG' AND is_active=1 ORDER BY sort_order", [country])
                    todo = [dict(zip(["id", "source_key", "mnemonic", "endpoint_url", "unit_multiplier", "frequency"], r), country_iso3=country) for r in cur.fetchall()]
                    for row in todo:
                        if only_series and only_series not in (row["id"], row["mnemonic"]):
                            continue
                        res = fetch_store(conn, cfg, row, run_id, backfill, log)
                        if res["ok"]:
                            stats["series_ok"] += 1
                            stats["obs_new"] += res["new"]
                            stats["obs_revised"] += res["revised"]
                            log(f"{row['id']}: +{res['new']} new, {res['revised']} revised, {res['same']} unchanged")
                        else:
                            stats["series_failed"] += 1
                            notes.append(f"{row['id']}: {res['error']}")
                if source in ("all", "imf"):
                    imf_info[country] = discover_imf(conn, cfg, country, codelist, log)
                    cur.execute("SELECT id, source_key, mnemonic, endpoint_url, unit_multiplier, frequency, country_iso3 FROM app_cr_series WHERE country_iso3=:1 AND source_key='IMF' AND is_active=1 ORDER BY sort_order", [country])
                    for r in cur.fetchall():
                        row = dict(zip(["id", "source_key", "mnemonic", "endpoint_url", "unit_multiplier", "frequency", "country_iso3"], r))
                        if only_series and only_series not in (row["id"], row["mnemonic"]):
                            continue
                        res = fetch_store(conn, cfg, row, run_id, backfill, log)
                        if res["ok"]:
                            stats["series_ok"] += 1
                            stats["obs_new"] += res["new"]
                            stats["obs_revised"] += res["revised"]
                            log(f"{row['id']}: +{res['new']} new, {res['revised']} revised, {res['same']} unchanged")
                        else:
                            stats["series_failed"] += 1
                            notes.append(f"{row['id']}: {res['error']}")
            for sk in ("BOG", "IMF", "FILE"):
                if (sk == "BOG" and source in ("all", "bog")) or (sk == "IMF" and source in ("all", "imf")) or (sk == "FILE" and source in ("all", "file")):
                    s = analyse_source(conn, cfg, country, sk, log)
                    if s:
                        log(f"{country} {sk}: {s['sector_count']} sectors, common period {s['common_period']}, total valid: {s['total'].get('valid')}")
            update_country_status(conn, cfg, country, imf_info.get(country), log)
    except Exception as e:
        stats["series_failed"] += 1
        notes.append(f"run stopped: {str(e)[:500]}")
        log(f"run stopped: {e}")
    status = finish_run(conn, run_id, stats, notes)
    log(f"credit run {run_id}: {status} ok={stats['series_ok']} failed={stats['series_failed']} new={stats['obs_new']} revised={stats['obs_revised']}")
    return {"run_id": run_id, "status": status, **stats}


