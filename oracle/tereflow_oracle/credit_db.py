def create_tables(conn, log=print) -> None:
    cur = conn.cursor()
    for s in DDL:
        try:
            cur.execute(s)
            log("created: " + s.split("(")[0].strip())
        except Exception as e:  # already there is fine
            if "ORA-00955" in str(e):
                continue
            raise
    conn.commit()


def _clean(v):
    return None if v is None or (isinstance(v, str) and v.strip() == "") else v


