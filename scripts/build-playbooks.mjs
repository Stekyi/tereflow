import { readFileSync, writeFileSync } from 'node:fs';

const SRC = process.argv[2];
const OUT = 'data/playbooks.sql';

function extractArray(text) {
  const candidates = [];
  for (const m of text.matchAll(/```(?:json)?\s*\n([\s\S]*?)```/g)) candidates.push(m[1]);
  for (const m of text.matchAll(/\[\s*\{/g)) {
    const start = m.index;
    let depth = 0;
    let inStr = false;
    let esc = false;
    for (let i = start; i < text.length; i++) {
      const ch = text[i];
      if (esc) { esc = false; continue; }
      if (ch === '\\') { esc = true; continue; }
      if (ch === '"') { inStr = !inStr; continue; }
      if (inStr) continue;
      if (ch === '[') depth++;
      else if (ch === ']') {
        depth--;
        if (depth === 0) { candidates.push(text.slice(start, i + 1)); break; }
      }
    }
  }
  let best = null;
  for (const c of candidates) {
    try {
      const parsed = JSON.parse(c.trim());
      if (Array.isArray(parsed) && parsed[0]?.slug && (!best || parsed.length > best.length)) {
        best = parsed;
      }
    } catch {
      /* skip */
    }
  }
  return best;
}

const q = (v) => (v == null || v === '' ? 'NULL' : `'${String(v).replace(/'/g, "''")}'`);

function slugify(s) {
  return String(s)
    .toLowerCase()
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
    .slice(0, 60);
}

const text = readFileSync(SRC, 'utf8');
const books = extractArray(text);
if (!books) {
  console.error('No playbook array found');
  process.exit(1);
}

const warnings = [];
const lines = [
  '-- Tereflow playbooks',
  '-- Generated by scripts/build-playbooks.mjs from verified research output.',
  '-- Every claim is attributed to a real institutional publication, checked live.',
  '',
  'DELETE FROM playbooks;',
  '',
];

let count = 0;
const seen = new Set();

for (const b of books) {
  if (!b?.title || !Array.isArray(b.sections) || b.sections.length === 0) {
    warnings.push(`skipped malformed: ${JSON.stringify(b).slice(0, 80)}`);
    continue;
  }
  const slug = slugify(b.slug || b.title);
  if (seen.has(slug)) {
    warnings.push(`duplicate slug skipped: ${slug}`);
    continue;
  }
  seen.add(slug);

  // Build the markdown body and collect every citation used anywhere in it.
  const allSources = new Map();
  const md = [];
  for (const s of b.sections) {
    if (!s?.heading || !s?.body) continue;
    // Em-dashes in headings read as machine-written. A colon says the same thing.
    const heading = String(s.heading)
      .replace(/\s+[—–]\s+/g, ': ')
      .replace(/\s+[—–]\s*/g, ': ')
      .trim();
    md.push(`## ${heading}`);
    md.push('');
    md.push(String(s.body).replace(/\s+[—–]\s+/g, ', ').trim());
    const srcs = Array.isArray(s.sources) ? s.sources : [];
    if (srcs.length) {
      md.push('');
      md.push(
        'Source: ' +
          srcs
            .filter((x) => x?.url && /^https?:\/\//i.test(x.url))
            .map((x) => `[${x.title ?? x.publisher ?? 'link'}](${x.url})`)
            .join(' · '),
      );
    }
    md.push('');
    for (const x of [...srcs, ...(Array.isArray(b.key_sources) ? b.key_sources : [])]) {
      if (x?.url && /^https?:\/\//i.test(x.url)) allSources.set(x.url, x);
    }
  }

  const body = md.join('\n').trim();
  if (!body) {
    warnings.push(`empty body: ${slug}`);
    continue;
  }

  const words = body.split(/\s+/).length;
  const minutes = Math.max(2, Math.round(words / 200));

  // First two playbooks stay free so the library is not a blank paywall.
  const premium = count < 2 ? 0 : 1;

  const iso3 = /^[A-Za-z]{3}$/.test(b.country_iso3 ?? '') ? b.country_iso3.toUpperCase() : null;
  const hs = b.hs_code ? String(b.hs_code).padStart(2, '0').slice(0, 2) : null;

  lines.push(
    `INSERT INTO playbooks (id, slug, title, sector, hs_code, country_iso3, summary, body_md, sources, author_name, author_credential, premium_only, reading_minutes, published_at, updated_at) VALUES (` +
      [
        q(`pb_${slug}`.slice(0, 60)),
        q(slug),
        q(b.title),
        q(b.sector),
        q(hs),
        q(iso3),
        q(b.summary),
        q(body),
        q(JSON.stringify([...allSources.values()])),
        q('Compiled from institutional trade guidance'),
        q(
          [...new Set([...allSources.values()].map((s) => s.publisher).filter(Boolean))]
            .slice(0, 6)
            .join(', '),
        ),
        premium,
        minutes,
        "datetime('now')",
        "datetime('now')",
      ].join(', ') +
      ');',
  );
  count++;
}

writeFileSync(OUT, lines.join('\n') + '\n', 'utf8');

console.log(`Wrote ${OUT}`);
console.log(`Playbooks: ${count} (${Math.min(2, count)} free, ${Math.max(0, count - 2)} premium)`);
if (warnings.length) {
  console.log(`Warnings (${warnings.length}):`);
  for (const w of warnings) console.log(`  - ${w}`);
}
