// Bundles tools/finance-toolkit and tools/national-toolkit into worker/generated/toolkit-bundle.ts so the Worker can serve them as zips.
import { readFileSync, writeFileSync, mkdirSync, readdirSync, statSync } from 'node:fs';
const sets = {
  finance: ['tools/finance-toolkit', ['finance.cmd', 'finance_tool.py', 'finance_config.json', 'requirements.txt', 'README.txt']],
  national: ['tools/national-toolkit', ['national.cmd', 'national_tool.py', 'national_config.json', 'requirements.txt', 'README.txt']],
};
const out = {};
// The rule files always come from templates/, the single source the loaders use.
const path = (dir, n) => (n.endsWith('_config.json') ? `templates/${n}` : `${dir}/${n}`);
for (const [k, [dir, names]] of Object.entries(sets)) out[k] = Object.fromEntries(names.map((n) => [n, readFileSync(path(dir, n), 'utf8')]));
// The pipeline kit: the Oracle pipeline code and loaders as they are in this repository, plus a launcher.
// Text files only; no wallet, no .env, nothing secret.
const kit = {};
const walk = (dir, keep) => {
  for (const n of readdirSync(dir)) {
    const f = `${dir}/${n}`;
    if (statSync(f).isDirectory()) { if (n !== '__pycache__' && n !== 'tests') walk(f, keep); } else if (keep.test(n)) kit[f] = readFileSync(f, 'utf8');
  }
};
walk('oracle/tereflow_oracle', /\.(py|json)$/);
walk('oracle/schema', /\.sql$/);
walk('oracle/ords', /\.plsql$/);
walk('templates', /\.(json|csv)$/);
for (const f of ['oracle/requirements.txt', 'scripts/finance/bank_load.py', 'scripts/finance/bank_template.py', 'scripts/national/national_load.py']) kit[f] = readFileSync(f, 'utf8');
for (const n of ['pipeline.cmd', 'README.txt', 'env.example']) kit[n] = readFileSync(`tools/pipeline-kit/${n}`, 'utf8');
out.pipeline = kit;
mkdirSync('worker/generated', { recursive: true });
writeFileSync('worker/generated/toolkit-bundle.ts',
  '// Generated by scripts/build-toolkits.mjs. Do not edit; edit tools/*-toolkit and run npm run toolkits:build.\n' +
  `export const TOOLKIT_FILES: Record<'finance' | 'national' | 'pipeline', Record<string, string>> = ${JSON.stringify(out)};\n`);
console.log('toolkit bundle written');