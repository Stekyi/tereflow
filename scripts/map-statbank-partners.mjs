/**
 * Match this application's country names to the strings Ghana StatBank expects.
 *
 *   node scripts/map-statbank-partners.mjs
 *
 * A partner name that does not match is not an error anybody sees. The API
 * returns a cube with nothing in it, and that country quietly contributes zero
 * to every share and every ranking. So the mapping is generated from the live
 * dimension list and the leftovers are printed for a person to decide, rather
 * than being guessed in a config file.
 */
import { openDb, q } from './dbq.mjs';

const ENDPOINT = 'https://statsbank.statsghana.gov.gh/api/v1/en/Trade/trade_detail_hs2.px';

const meta = await (await fetch(ENDPOINT, { signal: AbortSignal.timeout(30_000) })).json();
const partners = meta.variables
  .find((v) => v.code === 'Partner_Country')
  .values.filter((p) => p !== 'All Partner Countries');

const db = openDb();
const rows = q(
  db,
  "SELECT name, iso3 FROM entities WHERE kind='country' AND is_active=1 AND iso3 IS NOT NULL AND iso3 <> 'GHA' ORDER BY name",
);
db.close();

/** Fold to letters only, so punctuation and case cannot decide a match. */
const fold = (s) => s.toLowerCase().replace(/[^a-z]/g, '');

const byFolded = new Map();
for (const p of partners) byFolded.set(fold(p), p);

// Names the two lists genuinely disagree on. Each one was checked against the
// live dimension list rather than assumed.
const KNOWN = {
  'United States': 'United States of America',
  'South Korea': 'Republic of Korea',
  Vietnam: 'Viet Nam',
  Tanzania: 'United Republic of Tanzania',
  'DR Congo': 'Democratic Republic of the Congo',
  Taiwan: 'China, Taiwan Province of',
  Bolivia: 'Bolivia (Plurinational State of)',
  Venezuela: 'Venezuela (Bolivarian Republic of)',
  'Micronesia (Federated States of)': 'Micronesia (Federated States of)',
  Turkey: 'Turkiye',
};

const matched = [];
const unmatched = [];

for (const r of rows) {
  const direct = byFolded.get(fold(r.name));
  if (direct) {
    matched.push({ app: r.name, source: direct, iso3: r.iso3, how: 'exact' });
    continue;
  }
  const known = KNOWN[r.name] && byFolded.get(fold(KNOWN[r.name]));
  if (known) {
    matched.push({ app: r.name, source: known, iso3: r.iso3, how: 'mapped' });
    continue;
  }
  // Offer the nearest candidates so a person can judge, rather than the script
  // picking something plausible and wrong.
  const needle = fold(r.name).slice(0, 5);
  const near = partners.filter((p) => fold(p).includes(needle)).slice(0, 4);
  unmatched.push({ app: r.name, iso3: r.iso3, near });
}

console.log(`StatBank offers ${partners.length} partners.`);
console.log(`This app has ${rows.length} active countries besides Ghana.`);
console.log(`Matched ${matched.length}, unmatched ${unmatched.length}.\n`);

if (unmatched.length) {
  console.log('Not matched. Decide these by hand rather than guessing:');
  for (const u of unmatched) {
    console.log(`  ${u.app} (${u.iso3}) -> ${u.near.length ? u.near.map((n) => `"${n}"`).join(', ') : 'nothing similar'}`);
  }
  console.log('');
}

console.log('// Generated by scripts/map-statbank-partners.mjs');
console.log('export const GHANA_PARTNERS: PartnerMapping[] = [');
for (const m of matched.sort((a, b) => a.app.localeCompare(b.app))) {
  const note = m.how === 'mapped' ? ' // name differs from ours' : '';
  console.log(`  { app_name: ${JSON.stringify(m.app)}, source_name: ${JSON.stringify(m.source)}, iso3: ${JSON.stringify(m.iso3)} },${note}`);
}
console.log('];');
