"""National statistics loader: monthly or quarterly trade series from a country's own statistics office.

    python scripts/national/national_load.py create-tables
    python scripts/national/national_load.py make   [--out templates/national_template.xlsx]
    python scripts/national/national_load.py source ISO3 "Source name" --frequency monthly|quarterly|annual [--url URL] [--note TEXT]
    python scripts/national/national_load.py check  FILE.xlsx|FILE.csv [--frequency monthly|quarterly|annual] [--report problems.csv]
    python scripts/national/national_load.py load   FILE.xlsx|FILE.csv [--dry-run] [--replace]
    python scripts/national/national_load.py freshness

`check` needs no database. `load` requires the country's source to be registered first (so its update frequency is known),
checks every row against that frequency, refuses the whole file if any row is bad, and stores nothing it was not given.
`freshness` records the latest Comtrade year per country and flow, which the public Data sources page shows next to the
national series. Nothing here scrapes or guesses: a person supplies the file, the scripts validate and store it.
Run from the repo root; Oracle credentials come from the usual .env.
"""
from __future__ import annotations

import argparse
import csv
import json
import re
import sys
import uuid
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "oracle"))
CONFIG = ROOT / "templates" / "national_config.json"

DDL = [
    """CREATE TABLE app_nat_sources (country_iso3 VARCHAR2(3) PRIMARY KEY, source_name VARCHAR2(200) NOT NULL, source_url VARCHAR2(400),
       frequency VARCHAR2(10) NOT NULL, note VARCHAR2(400), is_active NUMBER DEFAULT 1,
       created_at VARCHAR2(30) DEFAULT TO_CHAR(SYSTIMESTAMP AT TIME ZONE 'UTC','YYYY-MM-DD HH24:MI:SS'))""",
    """CREATE TABLE app_nat_uploads (id VARCHAR2(40) PRIMARY KEY, filename VARCHAR2(300), rows_read NUMBER, rows_loaded NUMBER,
       status VARCHAR2(20), uploaded_by VARCHAR2(200),
       uploaded_at VARCHAR2(30) DEFAULT TO_CHAR(SYSTIMESTAMP AT TIME ZONE 'UTC','YYYY-MM-DD HH24:MI:SS'))""",
    """CREATE TABLE app_nat_series (id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY, country_iso3 VARCHAR2(3) NOT NULL,
       flow VARCHAR2(1) NOT NULL, period VARCHAR2(10) NOT NULL, hs_code VARCHAR2(6) NOT NULL, value_usd NUMBER NOT NULL,
       source_note VARCHAR2(400) NOT NULL, upload_id VARCHAR2(40),
       ingested_at VARCHAR2(30) DEFAULT TO_CHAR(SYSTIMESTAMP AT TIME ZONE 'UTC','YYYY-MM-DD HH24:MI:SS'))""",
    "CREATE INDEX app_nat_series_idx ON app_nat_series(country_iso3, flow, hs_code, period)",
    "CREATE INDEX app_nat_series_upl ON app_nat_series(upload_id)",
    """CREATE TABLE app_data_freshness (country_iso3 VARCHAR2(3) NOT NULL, flow VARCHAR2(1) NOT NULL, comtrade_latest_year NUMBER,
       comtrade_years NUMBER, updated_at VARCHAR2(30) DEFAULT TO_CHAR(SYSTIMESTAMP AT TIME ZONE 'UTC','YYYY-MM-DD HH24:MI:SS'),
       CONSTRAINT app_data_freshness_pk PRIMARY KEY (country_iso3, flow))""",
]

PERIODS = {"monthly": re.compile(r"^\d{4}-(0[1-9]|1[0-2])$"), "quarterly": re.compile(r"^\d{4}-Q[1-4]$"), "annual": re.compile(r"^\d{4}$")}
HS = re.compile(r"^(TOTAL|\d{2}|\d{4}|\d{6})$")


def load_config() -> dict:
    return json.loads(CONFIG.read_text(encoding="utf-8"))


def read_rows(path: Path) -> list[dict]:
    if path.suffix.lower() == ".csv":
        with path.open(newline="", encoding="utf-8-sig") as fh:
            return [{(k or "").strip(): v for k, v in r.items()} for r in csv.DictReader(fh)]
    from openpyxl import load_workbook
    wb = load_workbook(path, read_only=True, data_only=True)
    ws = wb["Data"] if "Data" in wb.sheetnames else wb.worksheets[0]
    it = ws.iter_rows(values_only=True)
    head = [str(h).strip() if h is not None else "" for h in next(it, [])]
    return [dict(zip(head, r)) for r in it if r and any(v not in (None, "") for v in r)]


def validate(cfg: dict, rows: list[dict], freq_by_country: dict[str, str] | None, default_freq: str | None):
    """Returns the problems as (row, column, message). freq_by_country is None for a database-free check."""
    problems: list[tuple[int, str, str]] = []
    if rows:
        missing = [c for c in cfg["columns"] if c not in rows[0]]
        if missing:
            return [(1, "header", f"missing column(s): {', '.join(missing)}")]
    seen = set()
    for i, r in enumerate(rows, start=2):
        g = lambda c: str(r.get(c) if r.get(c) is not None else "").strip()
        for c in cfg["required"]:
            if not g(c):
                problems.append((i, c, "required value is empty"))
        iso, flow, period, hs = g("country_iso3"), g("flow"), g("period"), g("hs_code")
        if iso and not re.fullmatch(r"[A-Z]{3}", iso):
            problems.append((i, "country_iso3", f"'{iso}' must be three capital letters"))
        if flow and flow not in cfg["flows"]:
            problems.append((i, "flow", f"'{flow}' must be one of: {', '.join(cfg['flows'])} (X exports, M imports)"))
        if hs and not HS.match(hs):
            problems.append((i, "hs_code", f"'{hs}' must be TOTAL or a 2, 4 or 6 digit HS code"))
        freq = (freq_by_country or {}).get(iso) or default_freq
        if freq_by_country is not None and iso and iso not in freq_by_country:
            problems.append((i, "country_iso3", f"no national source registered for {iso}; register it first"))
        if period:
            if freq:
                if not PERIODS[freq].match(period):
                    problems.append((i, "period", f"'{period}' does not match {freq}: {cfg['period_formats'][freq]}"))
            elif not any(p.match(period) for p in PERIODS.values()):
                problems.append((i, "period", f"'{period}' is not a valid period"))
        try:
            v = float(g("value_usd"))
            if v < 0:
                problems.append((i, "value_usd", "must not be negative"))
        except ValueError:
            if g("value_usd"):
                problems.append((i, "value_usd", f"'{g('value_usd')}' is not a number (US dollars, plain digits)"))
        key = (iso, flow, period, hs)
        if key in seen:
            problems.append((i, "row", "duplicate of an earlier row (same country, flow, period and product)"))
        seen.add(key)
    return problems


def make(cfg: dict, out: Path) -> None:
    from openpyxl import Workbook
    wb = Workbook()
    ws = wb.active; ws.title = "Data"; ws.append(cfg["columns"])
    ex = wb.create_sheet("Example"); ex.append(cfg["columns"])
    ex.append(["GHA", "X", "2026-03", "TOTAL", 1250000000, "Ghana Statistical Service, March 2026 release, table 2"])
    ex.append(["GHA", "X", "2026-03", "1801", 310000000, "Ghana Statistical Service, March 2026 release, table 4"])
    nt = wb.create_sheet("Notes")
    nt.append(["flow", "X = exports, M = imports"])
    nt.append(["period", "; ".join(f"{k}: {v}" for k, v in cfg["period_formats"].items())])
    nt.append(["hs_code", cfg["hs_code"]])
    nt.append(["value_usd", "US dollars, plain digits. Convert local currency first and say how in source_note."])
    nt.append(["source_note", "Where the figure came from: release, table, date. Required on every row."])
    nt.append(["priority countries", ", ".join(cfg["priority_countries"])])
    out.parent.mkdir(parents=True, exist_ok=True); wb.save(out)


def connect():
    from tereflow_oracle.config import load_env
    from tereflow_oracle import db
    load_env()
    return db.connect()


def main(argv=None) -> int:
    p = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    sub = p.add_subparsers(dest="cmd", required=True)
    sub.add_parser("create-tables"); sub.add_parser("freshness")
    m = sub.add_parser("make"); m.add_argument("--out", default=str(ROOT / "templates" / "national_template.xlsx"))
    s = sub.add_parser("source"); s.add_argument("iso3"); s.add_argument("name"); s.add_argument("--frequency", required=True, choices=["monthly", "quarterly", "annual"]); s.add_argument("--url"); s.add_argument("--note")
    c = sub.add_parser("check"); c.add_argument("file"); c.add_argument("--frequency", choices=["monthly", "quarterly", "annual"]); c.add_argument("--report")
    l = sub.add_parser("load"); l.add_argument("file"); l.add_argument("--dry-run", action="store_true"); l.add_argument("--replace", action="store_true")
    a = p.parse_args(argv)
    cfg = load_config()
    if a.cmd == "make":
        make(cfg, Path(a.out)); print(f"wrote {a.out}"); return 0
    if a.cmd == "check":
        rows = read_rows(Path(a.file)); probs = validate(cfg, rows, None, a.frequency)
        print(f"{a.file}: {len(rows)} data row(s), {len(probs)} problem(s)")
        for r, col, msg in probs[:200]: print(f"  row {r} [{col}]: {msg}")
        if a.report:
            with open(a.report, "w", newline="", encoding="utf-8") as fh:
                w = csv.writer(fh); w.writerow(["row", "column", "problem"]); w.writerows(probs)
        print("VALID" if rows and not probs else "NOT VALID"); return 0 if rows and not probs else 1
    conn = connect(); cur = conn.cursor()
    if a.cmd == "create-tables":
        for d in DDL:
            try: cur.execute(d); print("created:", d.split("(")[0].strip())
            except Exception as e:
                if "ORA-00955" not in str(e): raise
        conn.commit(); return 0
    if a.cmd == "source":
        cur.execute("DELETE FROM app_nat_sources WHERE country_iso3 = :1", [a.iso3.upper()])
        cur.execute("INSERT INTO app_nat_sources (country_iso3, source_name, source_url, frequency, note) VALUES (:1,:2,:3,:4,:5)", [a.iso3.upper(), a.name, a.url, a.frequency, a.note])
        conn.commit(); print("saved", a.iso3.upper()); return 0
    if a.cmd == "freshness":
        cur.execute("SELECT reporter_iso3, flow, MAX(year), COUNT(DISTINCT year) FROM tf_trade_facts GROUP BY reporter_iso3, flow")
        rows = cur.fetchall()
        for iso, flow, ly, ny in rows:
            cur.execute("""MERGE INTO app_data_freshness t USING (SELECT :1 c, :2 f FROM dual) s ON (t.country_iso3 = s.c AND t.flow = s.f)
                           WHEN MATCHED THEN UPDATE SET comtrade_latest_year = :3, comtrade_years = :4, updated_at = TO_CHAR(SYSTIMESTAMP AT TIME ZONE 'UTC','YYYY-MM-DD HH24:MI:SS')
                           WHEN NOT MATCHED THEN INSERT (country_iso3, flow, comtrade_latest_year, comtrade_years) VALUES (s.c, s.f, :5, :6)""", [iso, flow, ly, ny, ly, ny])
        conn.commit(); print(f"freshness recorded for {len(rows)} country-flows"); return 0
    path = Path(a.file); rows = read_rows(path)
    cur.execute("SELECT country_iso3, frequency FROM app_nat_sources WHERE is_active = 1")
    freq = dict(cur.fetchall())
    probs = validate(cfg, rows, freq, None)
    print(f"{path.name}: {len(rows)} data row(s), {len(probs)} problem(s)")
    for r, col, msg in probs[:100]: print(f"  row {r} [{col}]: {msg}")
    if probs or not rows: print("NOT LOADED"); return 1
    if a.dry_run: print(f"dry run: {len(rows)} row(s) would be loaded"); return 0
    uid = "nup_" + uuid.uuid4().hex[:22]
    cur.execute("INSERT INTO app_nat_uploads (id, filename, rows_read, rows_loaded, status, uploaded_by) VALUES (:1,:2,:3,:4,'loaded','script')", [uid, path.name, len(rows), len(rows)])
    for r in rows:
        k = [str(r["country_iso3"]).strip(), str(r["flow"]).strip(), str(r["period"]).strip(), str(r["hs_code"]).strip()]
        if a.replace:
            cur.execute("DELETE FROM app_nat_series WHERE country_iso3 = :1 AND flow = :2 AND period = :3 AND hs_code = :4", k)
        cur.execute("INSERT INTO app_nat_series (country_iso3, flow, period, hs_code, value_usd, source_note, upload_id) VALUES (:1,:2,:3,:4,:5,:6,:7)",
                    k + [float(r["value_usd"]), str(r["source_note"]).strip(), uid])
    conn.commit(); print(f"loaded {len(rows)} row(s) as {uid}"); return 0


if __name__ == "__main__":
    sys.exit(main())